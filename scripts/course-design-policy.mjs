#!/usr/bin/env node
// Validates the cross-client course-design policy and regenerates the compact Agent Skill inventory.
//
//   node scripts/course-design-policy.mjs
//   node scripts/course-design-policy.mjs --check
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const policyPath = join(root, "api/packages/course-builder/resources/course-design/policy.json");
const outputPath = join(root, ".cursor/skills/ulams-course-designer/references/capabilities.md");
const policy = JSON.parse(readFileSync(policyPath, "utf8"));
const problems = [];

if (policy.version !== 1) problems.push("version must be 1");
const shells = (policy.shells ?? []).map((shell) => shell.id);
if (JSON.stringify(shells) !== JSON.stringify(["course", "scroll", "slides"])) {
  problems.push("shells must be course, scroll, slides in that order");
}
const capabilities = policy.capabilities ?? [];
const ids = capabilities.map((capability) => capability.id);
if (new Set(ids).size !== ids.length) problems.push("capability ids must be unique");
const h5p = capabilities.filter((capability) => capability.runtime?.kind === "h5p-library");
if (h5p.length !== 54) problems.push(`expected 54 official H5P types, found ${h5p.length}`);
for (const capability of capabilities) {
  for (const key of ["id", "family", "label", "purpose", "authoring", "runtime", "tracking", "fallback", "accessibility", "citations"]) {
    if (capability[key] === undefined) problems.push(`${capability.id ?? "<unknown>"}: missing ${key}`);
  }
  if (capability.authoring === "api-generated" && capability.runtime?.kind === "h5p-library" && !["H5P.Blanks", "H5P.DragText", "H5P.Dialogcards"].includes(capability.runtime.key)) {
    problems.push(`${capability.id}: H5P API generation has no approved deterministic mapper`);
  }
}
if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}

const familyOrder = ["explain", "show", "recall", "arrange", "decide", "practise", "explore", "reflect", "integrate"];
const lines = [
  "# Course building-block inventory",
  "",
  "<!-- Generated by `node scripts/course-design-policy.mjs`; edit policy.json, not this file. -->",
  "",
  "The inventory is broader than the current generator. `api-generated` is safe for the Laravel",
  "pipeline; `agent-composed` uses an approved declarative component; `catalogue-reference` selects",
  "existing reviewed content; `author-import` and `manual` require author work; `unavailable` must use",
  "its fallback.",
  "",
  "## Learner experience shells",
  "",
  ...policy.shells.map((shell) => `- \`${shell.id}\` — **${shell.label}**: ${shell.useWhen}`),
  "",
];
for (const family of familyOrder) {
  const entries = capabilities.filter((capability) => capability.family === family);
  if (entries.length === 0) continue;
  lines.push(`## ${family[0].toUpperCase()}${family.slice(1)}`, "");
  for (const entry of entries) {
    lines.push(`- \`${entry.id}\` — **${entry.label}** · \`${entry.authoring}\`: ${entry.purpose} Fallback: ${entry.fallback}.`);
  }
  lines.push("");
}
lines.push(
  "## Sources",
  "",
  ...policy.sources.map((source) => `- [${source.title}](${source.href}) — checked ${source.checked}`),
  "",
);

const next = `${lines.join("\n")}\n`;
if (process.argv.includes("--check")) {
  const current = readFileSync(outputPath, "utf8");
  if (current !== next) {
    console.error("Course-design Agent Skill inventory is stale. Run `node scripts/course-design-policy.mjs`.");
    process.exit(1);
  }
  console.log(`Course-design policy is valid (${capabilities.length} capabilities; ${h5p.length} H5P types).`);
} else {
  writeFileSync(outputPath, next);
  console.log(`Course-design policy: wrote ${capabilities.length} capabilities (${h5p.length} H5P types).`);
}
